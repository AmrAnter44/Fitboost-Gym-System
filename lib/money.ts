/**
 * أدوات تقريب المبالغ المالية.
 *
 * الفلوس متخزّنة كـ Float في الـ DB، والحساب بـ IEEE-754 بيسبّب انحرافات
 * زي 4999.999999. round2 بتقرّب لأقرب قرشين (2 منازل عشرية) عند كل حفظ/حساب
 * عشان نتجنّب الانحراف ده.
 */
export function round2(n: number): number {
  return Math.round((Number(n) || 0) * 100) / 100
}
