// قاعدة موحّدة لحساب الإيرادات — عشان التقارير والتقفيل الشهري يقروا من نفس المكان.
//
// الإيصال بيتحسب في الإيرادات إلا لو كان ملغي (isCancelled) ومالوش طريقة استرجاع (refundMethod).
// يعني: الملغي اللي اترجعت فلوسه فعلاً بطريقة معيّنة بيتحسب (لأن الاسترجاع بيتسجّل كمصروف منفصل)،
// والملغي بدون استرجاع بيتشال خالص.
//
// لازم أي مكان بيحسب إجمالي إيرادات (تقارير / تقفيل / عمولات) يستخدم الدالة دي بدل فلترة يدوية
// عشان الأرقام تفضل متطابقة في كل الصفحات.
export function countsAsRevenue(r: { isCancelled?: boolean | null; refundMethod?: string | null }): boolean {
  return !(r.isCancelled && !r.refundMethod)
}
