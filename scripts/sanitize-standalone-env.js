// scripts/sanitize-standalone-env.js
// 🔒 بيتشغّل بعد `next build` (من postbuild.js).
// Next بينسخ .env بتاع جهاز الـ build جوه .next/standalone/.env — والملف ده بيتشحن
// مع الـ installer لكل الجيمات ومقروء في فولدر التسطيب. فبنسيب فيه إعدادات عامة بس،
// وبنفحص الـ build كله إن مفيش أي سر من .env اتحفر جوه أي ملف — لو لقينا، الـ build بيقف.

const fs = require('fs')
const path = require('path')

// اللي مسموح يتشحن (مش أسرار). أي حاجة تانية بتتشال.
const ALLOW = new Set([
  'DATABASE_URL', 'PORT', 'HOSTNAME', 'NODE_ENV', 'NEXT_TELEMETRY_DISABLED',
  'NEXT_PUBLIC_APP_URL', 'NEXT_PUBLIC_WEBSITE_URL', 'NEXT_PUBLIC_DOMAIN',
  'NEXT_PUBLIC_SUPPORT_WEBSITE', 'NEXT_PUBLIC_SUPPORT_WHATSAPP',
  'NEXT_PUBLIC_GITHUB_REPO_URL', 'NEXT_PUBLIC_GITHUB_RELEASES_URL',
  'FITBOOST_GATEWAY_URL',
  // ⚠️ OWNER_* مبقتش بتتشحن: حساب FitBoost Admin بيتحقق منه Control (باسورد + 2FA)
])

// قيم لو ظهرت في أي ملف في الـ build → وقف (أسرار حقيقية من .env الجهاز)
const SECRET_KEYS = [
  'SUPABASE_SERVICE_ROLE_KEY', 'NEXT_PUBLIC_SUPABASE_ANON_KEY', 'JWT_SECRET', 'GH_TOKEN', 'GITHUB_TOKEN',
  'B2_KEY_ID', 'B2_APPLICATION_KEY', 'OWNER_PASSWORD', 'OWNER_PASSWORD_HASH_B64', 'OWNER_PASSWORD_HASH',
  'INTERNAL_API_TOKEN', 'CRON_SECRET',
  'EMERGENCY_SIGNUP_SECRET',
]

function parse(file) {
  const out = []
  if (!fs.existsSync(file)) return out
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/)
    if (!m) continue
    out.push([m[1], m[2].trim().replace(/^(['"])(.*)\1$/, '$2')])
  }
  return out
}

function sanitize(standaloneEnv) {
  const kept = []
  const dropped = []
  for (const [k, v] of parse(standaloneEnv)) {
    if (ALLOW.has(k)) kept.push(`${k}=${JSON.stringify(v)}`)
    else dropped.push(k)
  }
  fs.writeFileSync(standaloneEnv, '# generated by scripts/sanitize-standalone-env.js — no secrets\n' + kept.join('\n') + '\n')
  return { kept: kept.length, dropped }
}

function* walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) {
      if (e.name === 'node_modules' || e.name === 'cache') continue
      yield* walk(p)
    } else if (/\.(js|mjs|cjs|json|html|txt|map|env|rsc|body|meta)$|^\.env/.test(e.name)) {
      yield p
    }
  }
}

function scan(roots, secrets) {
  const hits = []
  for (const root of roots) {
    if (!fs.existsSync(root)) continue
    for (const file of walk(root)) {
      const buf = fs.readFileSync(file)
      for (const [k, v] of secrets) if (buf.includes(v)) hits.push(`${k} → ${path.relative(process.cwd(), file)}`)
    }
  }
  return hits
}

function main() {
  const root = process.cwd()
  const standaloneEnv = path.join(root, '.next', 'standalone', '.env')
  if (fs.existsSync(standaloneEnv)) {
    const r = sanitize(standaloneEnv)
    console.log(`🔒 standalone .env: kept ${r.kept}, dropped ${r.dropped.length} (${r.dropped.join(', ') || '—'})`)
  }

  const secrets = parse(path.join(root, '.env'))
    .filter(([k, v]) => SECRET_KEYS.includes(k) && v && v.length >= 12)
  if (!secrets.length) return

  const hits = scan([path.join(root, '.next', 'standalone'), path.join(root, '.next', 'static')], secrets)
  if (hits.length) {
    console.error('\n❌ سر من .env اتحفر جوه الـ build — الـ build اتوقف عشان ميتشحنش:')
    for (const h of [...new Set(hits)].slice(0, 20)) console.error('   ' + h)
    process.exit(1)
  }
  console.log(`🔒 secret scan: ${secrets.length} secret(s) checked — none found in the build`)
}

if (require.main === module) main()
module.exports = { sanitize, parse, ALLOW }
