// ---- تحويل الأرقام العربية (لو وُجدت) لأرقام لاتينية ----
function toAsciiDigits(s) {
  return s.replace(/[٠-٩]/g, d => String(d.charCodeAt(0) - 0x0660))
          .replace(/[۰-۹]/g, d => String(d.charCodeAt(0) - 0x06F0))
}

// ---- إزالة علامات الاتجاه المخفية ----
function stripMarks(s) {
  return s.replace(/[‎‏‪-‮⁦-⁩ ]/g, '')
}

// ---- تطبيع رقم مصري لصيغة 01XXXXXXXXX ----
function normalizePhone(raw) {
  let digits = toAsciiDigits(raw).replace(/[^\d]/g, '')

  // 00 دولي في الأول
  if (digits.startsWith('00')) digits = digits.slice(2)
  // بادئة 20 (مصر) — 20 + 10 أرقام
  if (digits.length === 12 && digits.startsWith('20')) digits = '0' + digits.slice(2)
  // 10 أرقام بادئة 1 (ناقص الصفر)
  if (digits.length === 10 && digits.startsWith('1')) digits = '0' + digits

  // لازم يبقى موبايل مصري صحيح: 01 + (0/1/2/5) + 8 أرقام
  if (/^01[0125]\d{8}$/.test(digits)) return digits
  return null
}

// ---- قراءة الاسم والرقم من كل سطر ----
function parseLine(line) {
  const clean = stripMarks(line).replace(/\t+/g, '\t').trim()
  if (!clean) return null
  // الرقم = أول ظهور لـ + أو رقم لحد آخر السطر (بيسمح بمسافات جوّه الرقم)
  const m = clean.match(/^(.*?)[\s\t]*([+\d][\d\s+]*)$/)
  if (!m) return null
  const name = stripMarks(m[1]).trim()
  const phoneRaw = m[2].trim()
  if (!/\d/.test(phoneRaw)) return null
  return { name, phoneRaw }
}

async function main() {
  const prisma = new PrismaClient()
  const dbUrl = process.env.DATABASE_URL || '(من schema)'
  console.log('🗄️  الاستيراد على:', dbUrl.replace(/\?.*$/, ''))
  if (DRY_RUN) console.log('🧪 وضع المعاينة (Dry run) — مفيش كتابة فعلية\n')

  // نسخة احتياطية سريعة قبل الكتابة (best-effort)
  if (!DRY_RUN && (process.env.DATABASE_URL || '').startsWith('file:')) {
    try {
      const dbPath = process.env.DATABASE_URL.replace(/^file:/, '').replace(/\?.*$/, '')
      const stamp = new Date().toISOString().replace(/[:.]/g, '-')
      for (const suffix of ['', '-wal', '-shm']) {
        if (fs.existsSync(dbPath + suffix)) {
          fs.copyFileSync(dbPath + suffix, `${dbPath}.import-backup-${stamp}${suffix}`)
        }
      }
      console.log(`💾 اتعملت نسخة احتياطية: ${path.basename(dbPath)}.import-backup-${stamp}\n`)
    } catch (e) {
      console.warn('⚠️  فشلت النسخة الاحتياطية (هنكمل عادي):', e.message, '\n')
    }
  }

  const invalid = []          // أرقام غلط
  const byPhone = new Map()   // phone → name (dedup داخل القائمة)

  for (const line of RAW.split('\n')) {
    const parsed = parseLine(line)
    if (!parsed) continue
    if (/^name$/i.test(parsed.name) && /phone/i.test(parsed.phoneRaw)) continue // الهيدر

    const phone = normalizePhone(parsed.phoneRaw)
    if (!phone) {
      invalid.push({ name: parsed.name || '—', phoneRaw: parsed.phoneRaw })
      continue
    }

    const name = parsed.name || ''
    if (byPhone.has(phone)) {
      // تكرار — لو الاسم القديم فاضي والجديد فيه اسم، نكمّله
      if (!byPhone.get(phone) && name) byPhone.set(phone, name)
    } else {
      byPhone.set(phone, name)
    }
  }

  // الأرقام الموجودة بالفعل في الـ DB
  const existingRows = await prisma.visitor.findMany({ select: { phone: true } })
  const existing = new Set(existingRows.map(r => r.phone))

  const toInsert = []
  let skippedExisting = 0
  let placeholders = 0
  for (const [phone, name] of byPhone) {
    if (existing.has(phone)) { skippedExisting++; continue }
    let finalName = name
    if (!finalName) { finalName = NAME_PLACEHOLDER; placeholders++ }
    toInsert.push({ name: finalName, phone })
  }

  console.log('📊 ملخص:')
  console.log(`   • صفوف صالحة بعد إزالة التكرار: ${byPhone.size}`)
  console.log(`   • موجودين بالفعل (اتتخطوا):      ${skippedExisting}`)
  console.log(`   • هيتضافوا دلوقتي:               ${toInsert.length}`)
  console.log(`   • منهم باسم بديل "${NAME_PLACEHOLDER}":    ${placeholders}`)
  console.log(`   • أرقام مرفوضة (غلط):            ${invalid.length}`)

  if (invalid.length) {
    console.log('\n⚠️  أرقام مرفوضة (راجعها يدوياً):')
    for (const r of invalid) console.log(`     - ${r.name}: "${r.phoneRaw}"`)
  }

  if (DRY_RUN) {
    console.log('\n🧪 Dry run — مفيش حاجة اتكتبت. شيل --dry-run للتنفيذ.')
    await prisma.$disconnect()
    return
  }

  let created = 0, failed = 0
  for (const v of toInsert) {
    try {
      await prisma.visitor.create({
        data: { name: v.name, phone: v.phone, source: SOURCE, status: STATUS, notes: IMPORT_NOTE },
      })
      created++
    } catch (e) {
      // P2002 = تعارض uniqueness (اتضاف بالتوازي) — نتخطاه بهدوء
      if (e.code !== 'P2002') { failed++; console.warn(`   ✗ ${v.phone}: ${e.message}`) }
    }
  }

  console.log(`\n✅ تم. أُضيف ${created} زائر${failed ? ` (فشل ${failed})` : ''}.`)
  console.log(`ℹ️  كلهم متعلّمين بملاحظة "${IMPORT_NOTE}" — تقدر تلاقيهم أو ترجّعهم بيها لو حبيت.`)
  await prisma.$disconnect()
}

main().catch(err => {
  console.error('❌ خطأ عام في الاستيراد:', err)
  process.exit(1)
})
